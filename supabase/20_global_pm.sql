-- PM 직급을 한국 PM / 글로벌 PM 으로. (글로벌 = 미국·말레이시아 등 해외 전체)
-- 기존 '미국 PM' 은 '글로벌 PM' 으로 이관.
-- 실행 위치: aim 프로젝트 SQL Editor
-- ============================================================
update aim.staff set rank = '글로벌 PM' where rank = '미국 PM';
